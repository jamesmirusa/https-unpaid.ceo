#!/usr/bin/env python3
"""Stage 2A, Task 10: build chapter 2-3 scenes from tools/content/scenes/*.py.

Writes Yarn/<file>.yarn, Content/storylets_ch2.json / storylets_ch3.json, appends the Russian rows to
Yarn/Story-ru.csv (lock = first 8 hex of SHA-256 of the English text, as Yarn Spinner does) and lists the
new spoken line ids in tools/voice/pending.txt. Idempotent: rows and ids it owns are replaced.
"""
import csv
import hashlib
import importlib.util
import io
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "game", "Assets", "UnpaidCeo")
YARN = os.path.join(ROOT, "Yarn")
CONTENT = os.path.join(ROOT, "Content")
CSV_PATH = os.path.join(YARN, "Story-ru.csv")
PENDING = os.path.join(HERE, "..", "voice", "pending.txt")

SPEAKERS_RU = {
    "Unpaid CEO": "Unpaid CEO", "Ms. Lee": "Мисс Ли", "Rosa": "Роза", "Mia": "Миа", "Sam": "Сэм",
    "Mr. Whiskerton": "Мистер Вискертон", "Tony": "Тони", "Jay": "Джей", "Mom": "Мама",
}
FORBIDDEN = re.compile(r"[#{}\[\]<>]|//")


class S:
    """A scene: intro lines, then choices. Lines are (speaker or "", en, ru)."""
    def __init__(self, id, file, chapter_file, when, choices, intro, arc=None, weight=5, once=True, cooldown=0):
        self.id, self.file, self.chapter_file, self.when = id, file, chapter_file, when
        self.choices, self.intro, self.arc, self.weight, self.once, self.cooldown = choices, intro, arc, weight, once, cooldown


class C:
    """A choice: option text, effects, and the lines that follow it."""
    def __init__(self, id, en, ru, effects, *after):
        self.id, self.en, self.ru, self.effects, self.after = id, en, ru, effects, list(after)


def cash(c): return {"cash": c}
def stat(s, d): return {"stat": s, "delta": d}
def npc(n, d): return {"npc": n, "delta": d}
def fact(f): return {"setFact": f}
def clear(f): return {"clearFact": f}
def demand(f, m, industry="current"): return {"demand": {"factor": f, "months": m, "industry": industry}}
def staff(d): return {"staff": {"delta": d}}
def lesson(l): return {"lesson": l}
def reserve(c): return {"reserve": c}


def load_scenes():
    scenes = []
    folder = os.path.join(HERE, "scenes")
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".py"):
            continue
        spec = importlib.util.spec_from_file_location(name[:-3], os.path.join(folder, name))
        mod = importlib.util.module_from_spec(spec)
        mod.__dict__.update(S=S, C=C, cash=cash, stat=stat, npc=npc, fact=fact, clear=clear, demand=demand,
                            staff=staff, lesson=lesson, reserve=reserve)
        spec.loader.exec_module(mod)
        scenes += mod.SCENES
    return scenes


def ru_line(speaker, ru):
    return f"{SPEAKERS_RU[speaker]}: {ru}" if speaker else ru


def en_line(speaker, en):
    return f"{speaker}: {en}" if speaker else en


def lock(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:8]


def main():
    scenes = load_scenes()
    ids = [s.id for s in scenes]
    assert len(ids) == len(set(ids)), "duplicate scene id"

    files, storylets, rows, spoken = {}, {"ch2": [], "ch3": []}, [], []
    for s in scenes:
        files.setdefault(s.file, []).append(s)

    for fname, group in files.items():
        out = [f"// Chapters 2-3 ({fname}). Generated by tools/content/stage2_scenes.py from tools/content/scenes/.",
               "// Every option runs <<choose \"id\">>; its effects live in Content/storylets_ch2.json or storylets_ch3.json.",
               "// Russian text lives in Story-ru.csv; keep #line ids stable.", ""]
        for s in group:
            n = 0
            def add(speaker, en, ru, option=False, indent=""):
                nonlocal n
                n += 1
                lid = f"{s.id}_{n:02d}"
                text = en_line(speaker, en)
                assert not FORBIDDEN.search(text) and not FORBIDDEN.search(ru), f"{lid}: Yarn markup characters"
                assert speaker or ":" not in text[:31], f"{lid}: narration looks like a speaker line"
                out.append(f"{indent}{'-> ' if option else ''}{text} #line:{lid}")
                rows.append({"id": "line:" + lid, "text": ru_line(speaker, ru), "file": fname, "node": s.id,
                             "lineNumber": len(out), "lock": lock(text)})
                if not option:
                    spoken.append(lid)
                return "line:" + lid
            out += [f"title: {s.id}", "---"]
            for sp, en, ru in s.intro:
                add(sp, en, ru)
            choice_lines, choices = {}, {}
            for c in s.choices:
                assert c.effects, f"{s.id}/{c.id}: a choice needs a visible effect"
                choice_lines[c.id] = add("", c.en, c.ru, option=True)
                out.append(f"    <<choose \"{c.id}\">>")
                for sp, en, ru in c.after:
                    add(sp, en, ru, indent="    ")
                choices[c.id] = c.effects
            out += ["===", ""]
            entry = {"id": s.id, "yarnNode": s.id}
            if s.arc:
                entry["arc"] = s.arc
            entry["when"] = s.when
            entry["weight"] = s.weight
            if s.once:
                entry["once"] = True
            if s.cooldown:
                entry["cooldownMonths"] = s.cooldown
            entry["choices"] = choices
            entry["choiceLines"] = choice_lines
            storylets[s.chapter_file].append(entry)
        with open(os.path.join(YARN, fname + ".yarn"), "w", encoding="utf-8") as f:
            f.write("\n".join(out))

    for ch, items in storylets.items():
        with open(os.path.join(CONTENT, f"storylets_{ch}.json"), "w", encoding="utf-8") as f:
            f.write('{ "storylets": [\n' + ",\n".join("  " + json.dumps(x, ensure_ascii=False) for x in items) + "\n] }\n")

    # Russian string table: keep chapter-1 rows, replace this generator's rows.
    with open(CSV_PATH, encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        header = reader.fieldnames
        old = [r for r in reader if r["file"] not in files]
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=header, lineterminator="\n")
    w.writeheader()
    for r in old:
        w.writerow(r)
    for r in rows:
        w.writerow({"language": "ru", "comment": "", **r})
    with open(CSV_PATH, "w", encoding="utf-8", newline="") as f:
        f.write(buf.getvalue())

    # Voice to record in Task 14.
    keep = []
    if os.path.exists(PENDING):
        with open(PENDING, encoding="utf-8") as f:
            prefixes = tuple(s.id + "_" for s in scenes)
            keep = [ln.rstrip("\n") for ln in f if not ln.startswith(prefixes) and ln.strip() != "# Chapter 2-3 scene lines:"]
    with open(PENDING, "w", encoding="utf-8") as f:
        f.write("\n".join(keep + ["# Chapter 2-3 scene lines:"] + spoken) + "\n")

    print(f"scenes {len(scenes)} (ch2 {len(storylets['ch2'])}, ch3 {len(storylets['ch3'])}), lines {len(rows)}, spoken {len(spoken)}, files {sorted(files)}")


if __name__ == "__main__":
    main()
